export const MESSAGES: Record<Locale, Messages> = { en, vi };

export type MessageVars = Record<string, string | number>;

/**
 * Checks whether a raw value is a supported locale.
 * @param value - Raw value to check.
 * @returns `true` when the value is a supported locale.
 */
export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}

/**
 * Resolves a raw locale value, falling back when it is missing or unknown.
 * @param value - Raw locale value.
 * @param fallback - Locale used when the value is invalid.
 * @returns A supported locale.
 */
export function parseLocale(value: unknown, fallback: Locale = DEFAULT_LOCALE): Locale {
  return isLocale(value) ? value : fallback;
}

/**
 * Translates a message key and interpolates `{placeholder}` variables.
 * @param locale - Target locale.
 * @param key - Message key.
 * @param vars - Values used to replace placeholders.
 * @returns The translated message.
 */
export function translate(locale: Locale, key: MessageKey, vars?: MessageVars): string {
  const template = MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key;
  if (!vars) return template;
  return template.replaceAll(/\{(\w+)\}/gu, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}
